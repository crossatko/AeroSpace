#!/usr/bin/env bash
# Build a signed AeroSpace.app without Xcode (SwiftPM release build + hand-assembled bundle).
#
# Differences from build-release.sh (which needs xcodebuild):
#   - host architecture only (no universal binary)
#   - no Assets.car (actool is part of Xcode); the icon is AppIcon.icns made with iconutil
#   - the CLI is embedded at AeroSpace.app/Contents/Resources/bin/aerospace (symlink it onto PATH)
#   - no docs, man pages, shell completion or brew cask
# Same as the Xcode build: bundle id bobko.aerospace, LSUIElement, entitlements from
# resources/AeroSpace.entitlements, no hardened runtime, signed with a stable identity so the
# Accessibility grant survives rebuilds.
#
# Usage: script/build-local-app.sh [--codesign-identity NAME] [--build-version VERSION] [--out DIR]
# Result: <out>/AeroSpace.app (default out: .local-app). Install: ditto .local-app/AeroSpace.app /Applications/AeroSpace.app
# Needs a Swift toolchain on PATH (e.g. swiftly) and the identity in the login keychain.
set -euo pipefail
cd "$(dirname "$0")/.."

codesign_identity="aerospace-codesign-certificate"
build_version="$(git describe --tags --always | sed 's/^v//')"
out=".local-app"
while test $# -gt 0; do
    case $1 in
        --codesign-identity) codesign_identity="$2"; shift 2 ;;
        --build-version) build_version="$2"; shift 2 ;;
        --out) out="$2"; shift 2 ;;
        *) echo "Unknown option $1" >&2; exit 1 ;;
    esac
done

swift_cmd=(swift)
if ! command -v swift > /dev/null && command -v swiftly > /dev/null; then swift_cmd=(swiftly run swift); fi

generated=(Sources/Common/versionGenerated.swift Sources/Common/gitHashGenerated.swift)
restore_generated() { git checkout -- "${generated[@]}"; }
trap restore_generated EXIT

cat > Sources/Common/versionGenerated.swift <<EOF
// FILE IS GENERATED BY generate.sh
public let aeroSpaceAppVersion = "$build_version"
EOF
cat > Sources/Common/gitHashGenerated.swift <<EOF
// FILE IS GENERATED BY generate.sh
public let gitHash = "$(git rev-parse HEAD)"
public let gitShortHash = "$(git rev-parse --short HEAD)"
EOF

"${swift_cmd[@]}" build -c release --product aerospace
"${swift_cmd[@]}" build -c release --product AeroSpaceApp
bin_path="$("${swift_cmd[@]}" build -c release --show-bin-path)"

app="$out/AeroSpace.app"
rm -rf "$app"
mkdir -p "$app/Contents/MacOS" "$app/Contents/Resources/bin"
cp "$bin_path/AeroSpaceApp" "$app/Contents/MacOS/AeroSpace"
cp "$bin_path/aerospace" "$app/Contents/Resources/bin/aerospace"
cp docs/config-examples/default-config.toml "$app/Contents/Resources/"
printf 'APPL????' > "$app/Contents/PkgInfo"

# Icon: the asset catalog has one 1024 px PNG; scale it into an iconset.
iconset="$(mktemp -d)/AppIcon.iconset"
mkdir -p "$iconset"
src_icon=resources/Assets.xcassets/AppIcon.appiconset/icon.png
for size in 16 32 128 256 512; do
    sips -z $size $size "$src_icon" --out "$iconset/icon_${size}x${size}.png" > /dev/null
    sips -z $((size * 2)) $((size * 2)) "$src_icon" --out "$iconset/icon_${size}x${size}@2x.png" > /dev/null
done
iconutil -c icns "$iconset" -o "$app/Contents/Resources/AppIcon.icns"
rm -rf "$(dirname "$iconset")"

cat > "$app/Contents/Info.plist" <<EOF
<?xml version="1.0" encoding="UTF-8"?>
<!DOCTYPE plist PUBLIC "-//Apple//DTD PLIST 1.0//EN" "http://www.apple.com/DTDs/PropertyList-1.0.dtd">
<plist version="1.0">
<dict>
	<key>CFBundleDevelopmentRegion</key><string>en</string>
	<key>CFBundleExecutable</key><string>AeroSpace</string>
	<key>CFBundleIconFile</key><string>AppIcon</string>
	<key>CFBundleIdentifier</key><string>bobko.aerospace</string>
	<key>CFBundleInfoDictionaryVersion</key><string>6.0</string>
	<key>CFBundleName</key><string>AeroSpace</string>
	<key>CFBundlePackageType</key><string>APPL</string>
	<key>CFBundleShortVersionString</key><string>$build_version</string>
	<key>CFBundleVersion</key><string>$build_version</string>
	<key>CFBundleSupportedPlatforms</key><array><string>MacOSX</string></array>
	<key>LSMinimumSystemVersion</key><string>13.0</string>
	<key>LSUIElement</key><true/>
</dict>
</plist>
EOF
plutil -lint "$app/Contents/Info.plist" > /dev/null

xattr -cr "$app"   # stray xattrs (quarantine, Finder info) break codesign

# Sign inside out: the embedded CLI first, then the bundle (seals the CLI as a resource).
codesign --force --sign "$codesign_identity" --identifier bobko.aerospace.cli "$app/Contents/Resources/bin/aerospace"
codesign --force --sign "$codesign_identity" --entitlements resources/AeroSpace.entitlements "$app"
codesign --verify --strict --verbose=1 "$app"

echo "Built $app ($build_version, $(git rev-parse --short HEAD))"
